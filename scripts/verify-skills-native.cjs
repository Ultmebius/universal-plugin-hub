const { createRequire } = require('node:module');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
// Run with DSH's Node/Electron runtime; pass its package.json as the first argument.
const anchor = process.env.DSH_NATIVE_PACKAGE_JSON || process.argv[2];
if (!anchor) throw new Error('Pass the native DSH package.json path');
const runtime = createRequire(path.resolve(anchor));
(async () => {
  const { Context } = runtime('@deepseek-ai/cordis');
  const { SkillRegistry } = runtime('@deepseek-ai/dsh-skill');
  const { FileSystemSkillProvider } = runtime('@deepseek-ai/dsh-skill-filesystem');
  const { createScope } = runtime('@deepseek-ai/dsh-scope');
  const { createSkillsManager } = await import('../src/skills.js');
  const { findDshMainNodeModules } = await import('../src/install.js');
  const scopeModule = createRequire(path.join(findDshMainNodeModules(), '.universal-plugin-hub-resolve.cjs'))('@deepseek-ai/dsh-scope');
  if (scopeModule.createScope !== createScope) throw new Error('Resolved a different native scope module');
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'hub-native-'));
  process.env.DSH_HOME = path.join(temp, 'dsh');
  const root = path.join(temp, '.agents', 'skills');
  const file = path.join(root, 'apple-design', 'SKILL.md');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, '---\nname: apple-design\ndescription: Apple design\n---\nInstructions');
  const copy = path.join(root, 'apple-design', 'plugins', 'copy', 'SKILL.md');
  fs.mkdirSync(path.dirname(copy), { recursive: true });
  fs.copyFileSync(file, copy);
  const nested = path.join(root, 'apple-design', 'child', 'SKILL.md');
  fs.mkdirSync(path.dirname(nested), { recursive: true });
  fs.writeFileSync(nested, '---\nname: hidden-child\ndescription: Nested child\n---\nInstructions');
  fs.writeFileSync(path.join(root, 'flat.md'), '---\nname: flat\ndescription: Flat skill\n---\nInstructions');
  const ctx = new Context();
  const registry = new SkillRegistry(ctx);
  const manager = createSkillsManager(root);
  const dispose = manager.attach(registry);
  let disposeAgents;
  try {
    const items = await manager.list();
    const item = items.find(s => s.name === 'apple-design');
    if (items.length !== 2 || item.locations.length !== 1) throw new Error('Nested skills were discovered');
    if (!item.available || !item.enabled) throw new Error('Native registry did not discover fallback');
    registry.registerProvider(control => new FileSystemSkillProvider(ctx, control, { agentsHome: path.dirname(root), dshHome: process.env.DSH_HOME, watch: false }));
    const filesystem = (await registry.list()).filter(s => s.provider === 'filesystem' && s.path.startsWith(fs.realpathSync.native(root)));
    if (JSON.stringify(items.map(s => s.name).sort()) !== JSON.stringify(filesystem.map(s => s.name).sort())) throw new Error('Discovery differs from native DSH');
    const native = (await registry.list()).find(s => s.name === 'apple-design');
    if (native.provider !== 'filesystem') throw new Error('Fallback shadows native provider');
    await manager.toggle(item.id, false);
    const presetKey = {};
    const preset = createScope(ctx, presetKey);
    preset.ctx.skills.registerProvider(control => new FileSystemSkillProvider(preset.ctx, control, { agentsHome: path.dirname(root), dshHome: process.env.DSH_HOME, watch: false }));
    const agent = { id: 'scoped', session: { header: { cwd: temp } } };
    const agentScope = createScope(ctx, agent, { parent: presetKey });
    agent.ctx = agentScope.ctx;
    const beforeScopeFix = (await registry.list({ scope: agent, cwd: temp })).find(s => s.name === 'apple-design');
    if (!beforeScopeFix.invocation.userInvocable) throw new Error('Scoped bypass was not reproduced');
    const isolatedCtx = ctx.isolate('skills');
    const isolatedRegistry = new SkillRegistry(isolatedCtx);
    isolatedRegistry.registerProvider(control => new FileSystemSkillProvider(isolatedCtx, control, { agentsHome: path.dirname(root), dshHome: process.env.DSH_HOME, watch: false }));
    const isolatedAgent = { id: 'isolated', session: { header: { cwd: temp } } };
    isolatedAgent.ctx = createScope(ctx, isolatedAgent).ctx;
    disposeAgents = manager.attachAgents({ agents: { list: () => [agent, isolatedAgent], get: id => [agent, isolatedAgent].find(value => value.id === id) }, on: ctx.on.bind(ctx), get: name => name === 'agentPresets' ? { serviceFor: value => value === isolatedAgent ? isolatedRegistry : undefined } : undefined }, scopeModule.createScope);
    const scopedOff = (await registry.list({ scope: agent, cwd: temp })).find(s => s.name === 'apple-design');
    if (scopedOff.invocation.userInvocable || scopedOff.invocation.modelInvocable) throw new Error('Scoped invocation remains enabled');
    const isolatedOff = (await isolatedRegistry.list({ scope: isolatedAgent, cwd: temp })).find(s => s.name === 'apple-design');
    if (isolatedOff.invocation.userInvocable || isolatedOff.invocation.modelInvocable) throw new Error('Isolated registry bypassed disabled state');
    await ctx.serial('agent-preset/selected', agent.id);
    if ((await registry.list({ scope: agent, cwd: temp })).find(s => s.name === 'apple-design').invocation.userInvocable) throw new Error('Preset switch bypassed disabled state');
    const coldKey = {};
    const cold = createScope(ctx, coldKey);
    cold.ctx.skills.registerProvider(control => new FileSystemSkillProvider(cold.ctx, control, { agentsHome: path.dirname(root), dshHome: process.env.DSH_HOME, watch: false }));
    const coldOff = (await registry.list({ scope: coldKey, cwd: temp })).find(s => s.name === 'apple-design');
    if (coldOff.invocation.userInvocable || coldOff.invocation.modelInvocable) throw new Error('Cold preset catalog bypassed disabled state');
    const off = (await registry.list()).find(s => s.name === 'apple-design');
    if (off.invocation.userInvocable || off.invocation.modelInvocable) throw new Error('Native invocation remains enabled');
    const projectOff = (await registry.list({ cwd: path.dirname(path.dirname(root)) })).find(s => s.name === 'apple-design');
    if (projectOff.invocation.userInvocable || projectOff.invocation.modelInvocable) throw new Error('Native project discovery bypassed disabled state');
    await manager.toggle(item.id, true);
    const on = (await registry.list()).find(s => s.name === 'apple-design');
    if (on.provider !== 'filesystem' || !on.invocation.userInvocable) throw new Error('Native invocation was not restored');
    const scopedOn = (await registry.list({ scope: agent, cwd: temp })).find(s => s.name === 'apple-design');
    if (scopedOn.provider !== 'filesystem' || !scopedOn.invocation.userInvocable) throw new Error('Scoped native invocation was not restored');
    const isolatedOn = (await isolatedRegistry.list({ scope: isolatedAgent, cwd: temp })).find(s => s.name === 'apple-design');
    if (isolatedOn.provider !== 'filesystem' || !isolatedOn.invocation.userInvocable) throw new Error('Isolated native invocation was not restored');
    console.log(JSON.stringify({ names: items.map(s => s.name), matchesNative: true, nativeProvider: native.provider, reproducedScopedBypass: true, scopedDisabledUserAndModel: true, coldScopedDisabled: true, isolatedRegistryDisabled: true, sharedNativeScope: true, restoredNative: true, scopedRestoredNative: true }));
  } finally { await disposeAgents?.(); dispose(); await ctx.fiber.dispose(); fs.rmSync(temp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1 });
